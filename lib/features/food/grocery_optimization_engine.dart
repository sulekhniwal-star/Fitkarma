  /// Optimizes a weekly grocery list based on the user's monthly budget.
  /// Converts monthly budget to weekly cost limit (`monthlyBudgetInr / 4.33`).
  OptimizedGroceryList optimize({
    required List<GroceryItem> rawList,
    required double monthlyBudgetInr,
    required int dailyProteinTargetG,
  }) {
    final weeklyCostLimit = monthlyBudgetInr / 4.33;
    final initialCost = _calculateCost(rawList);

    if (initialCost <= weeklyCostLimit) {
      return OptimizedGroceryList(
        items: rawList,
        totalCostInr: double.parse(initialCost.toStringAsFixed(1)),
        weeklyCostLimitInr: double.parse(weeklyCostLimit.toStringAsFixed(1)),
        monthlyBudgetInr: monthlyBudgetInr,
        isWithinBudget: true,
        hasSwaps: false,
        swapsAppliedCount: 0,
        totalSavedInr: 0.0,
      );
    }

    // Heuristic protein-per-rupee optimization:
    // Sort items by costPerGramOfProtein descending, substitute expensive protein items (> ₹1.0 / g protein).
    final optimized = <GroceryItem>[];
    double accumulatedCost = 0.0;
    int swapsCount = 0;
    double initialProteinCostTotal = 0.0;
    double newProteinCostTotal = 0.0;

    for (final item in rawList) {
      if (item.category == GroceryCategory.protein &&
          item.costPerGramOfProtein > 1.0) {
        final substitute = _findCheaperProteinSubstitute(item);
        optimized.add(substitute);
        accumulatedCost += substitute.priceInr;
        swapsCount++;
        initialProteinCostTotal += item.priceInr;
        newProteinCostTotal += substitute.priceInr;
      } else {
        optimized.add(item);
        accumulatedCost += item.priceInr;
      }
    }

    final totalSaved = initialProteinCostTotal - newProteinCostTotal;
    final isBudgetMet = accumulatedCost <= weeklyCostLimit;

    final warning = !isBudgetMet
        ? 'Unable to meet target within ₹${monthlyBudgetInr.toInt()}/mo. Consider adjusting budget to ₹${(accumulatedCost * 4.33).round()}/mo.'
        : 'Swapped premium protein items to match ₹${monthlyBudgetInr.toInt()}/mo budget (Saved ~₹${totalSaved.round()}/wk).';

    return OptimizedGroceryList(
      items: optimized,
      totalCostInr: double.parse(accumulatedCost.toStringAsFixed(1)),
      weeklyCostLimitInr: double.parse(weeklyCostLimit.toStringAsFixed(1)),
      monthlyBudgetInr: monthlyBudgetInr,
      isWithinBudget: isBudgetMet,
      hasSwaps: swapsCount > 0,
      swapsAppliedCount: swapsCount,
      totalSavedInr: double.parse(totalSaved.toStringAsFixed(1)),
      budgetWarning: warning,
    );
  }

  /// Replaces expensive protein sources with high-yield budget options (Soya Chunks & Curd Mix).
  GroceryItem _findCheaperProteinSubstitute(GroceryItem expensiveItem) {
    // Example: Greek Yogurt (₹560 for 70g pro = ₹8.0/g) -> Soya Chunks & Double-Toned Curd (₹120 for 70g pro = ₹1.7/g)
    final substitutePrice = (expensiveItem.priceInr * 0.25).clamp(80.0, 180.0);
    return GroceryItem(
      id: '${expensiveItem.id}_sub',
      name: 'Soya Chunks & Double-Toned Curd Pack',
      quantityGrams: 1000,
      unit: '500g Soya + 1kg Curd',
      priceInr: substitutePrice,
      proteinG: expensiveItem.proteinG, // Preserves exact protein yield
      category: GroceryCategory.protein,
      isSwappedSubstitute: true,
      originalItemName: expensiveItem.name,
    );
  }

  double _calculateCost(List<GroceryItem> items) {
    return items.fold(0.0, (sum, item) => sum + item.priceInr);
  }
}
