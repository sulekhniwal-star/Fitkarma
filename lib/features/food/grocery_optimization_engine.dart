/// Food categories for organizing grocery shopping lists.
enum GroceryCategory {
  protein,
  dairyAndEggs,
  grainsAndLegumes,
  produceAndVeggies,
  pantryAndOils,
}

/// Supported Quick-Commerce delivery partners (§P16-E integration).
enum VendorPartner { blinkit, zepto, swiggyInstamart }

/// A single grocery line item.
class GroceryItem {
  const GroceryItem({
    required this.id,
    required this.name,
    required this.quantityGrams,
    required this.unit,
    required this.priceInr,
    required this.proteinG,
    required this.category,
    this.isPurchased = false,
    this.isSwappedSubstitute = false,
    this.originalItemName,
  });

  final String id;
  final String name;
  final double quantityGrams;
  final String unit;
  final double priceInr;
  final double proteinG;
  final GroceryCategory category;
  final bool isPurchased;
  final bool isSwappedSubstitute;
  final String? originalItemName;

  /// Calculated cost in INR per gram of protein.
  double get costPerGramOfProtein {
    if (proteinG <= 0) return 0.0;
    return priceInr / proteinG;
  }

  GroceryItem copyWith({
    String? id,
    String? name,
    double? quantityGrams,
    String? unit,
    double? priceInr,
    double? proteinG,
    GroceryCategory? category,
    bool? isPurchased,
    bool? isSwappedSubstitute,
    String? originalItemName,
  }) {
    return GroceryItem(
      id: id ?? this.id,
      name: name ?? this.name,
      quantityGrams: quantityGrams ?? this.quantityGrams,
      unit: unit ?? this.unit,
      priceInr: priceInr ?? this.priceInr,
      proteinG: proteinG ?? this.proteinG,
      category: category ?? this.category,
      isPurchased: isPurchased ?? this.isPurchased,
      isSwappedSubstitute: isSwappedSubstitute ?? this.isSwappedSubstitute,
      originalItemName: originalItemName ?? this.originalItemName,
    );
  }
}

/// Result payload generated by [GroceryOptimizationEngine].
class OptimizedGroceryList {
  const OptimizedGroceryList({
    required this.items,
    required this.totalCostInr,
    required this.weeklyCostLimitInr,
    required this.monthlyBudgetInr,
    required this.isWithinBudget,
    required this.hasSwaps,
    required this.swapsAppliedCount,
    required this.totalSavedInr,
    this.budgetWarning,
  });

  final List<GroceryItem> items;
  final double totalCostInr;
  final double weeklyCostLimitInr;
  final double monthlyBudgetInr;
  final bool isWithinBudget;
  final bool hasSwaps;
  final int swapsAppliedCount;
  final double totalSavedInr;
  final String? budgetWarning;
}

